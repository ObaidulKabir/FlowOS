                transport = "streamable-http",
                protocolVersion = "2025-03-26",
                endpoint = mcpPath,
                url = mcpUrl,
                documentation = mcpUrl,
                toolsEndpoint = mcpPath,
                connection = new
                {
                    jsonrpcUrl = mcpUrl,
