    private static async Task InitializePostgresPersistenceAsync(
        IServiceProvider serviceProvider,
        CancellationToken cancellationToken = default)
    {
        using var scope = serviceProvider.CreateScope();
        var context = scope.ServiceProvider.GetRequiredService<FlowOSDbContext>();
        if (!context.Database.IsRelational())
            return;

        var logger = scope.ServiceProvider
            .GetRequiredService<ILoggerFactory>()
            .CreateLogger("FlowOS.MCP.Startup");
        try
        {
            await context.Database.MigrateAsync(cancellationToken);
            var securityProvisioning = scope.ServiceProvider
                .GetRequiredService<FlowOS.Infrastructure.Services.Security.TenantSecurityProvisioningService>();
            await securityProvisioning.BackfillAsync(cancellationToken);
            var backfill = scope.ServiceProvider.GetRequiredService<WorkflowDefinitionLineageBackfillService>();
            var result = await backfill.BackfillAsync(cancellationToken);
            logger.LogInformation(
                "MCP workflow lineage backfill scanned {Scanned}, repaired {Repaired}, and created {Created} state-machine definitions.",
                result.DefinitionsScanned,
                result.DefinitionsRepaired,
                result.StateMachinesCreated);
        }
        catch (Exception ex)
        {
            logger.LogError(
                ex,
                "MCP PostgreSQL migration/security/lineage backfill failed; authorization and class-backed definitions remain fail-closed.");
        }
    }

    private static string ResolvePublicMcpUrl(HttpContext context)
    {
        var configuration = context.RequestServices.GetRequiredService<IConfiguration>();
        var origin = FlowOsPublicUrls.ResolveOrigin(
            configuration,
            context.Request.Scheme,
            context.Request.Host.Value,
            context.Request.Headers["X-Forwarded-Proto"].FirstOrDefault(),
            context.Request.Headers["X-Forwarded-Host"].FirstOrDefault());
        return FlowOsPublicUrls.McpEndpoint(origin);
    }

