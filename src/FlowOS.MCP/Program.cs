    static async Task Main(string[] args)
    {
        var transport = Environment.GetEnvironmentVariable("MCP_TRANSPORT") ?? "stdio";
        if (string.Equals(transport, "http", StringComparison.OrdinalIgnoreCase))
            await RunHttpAsync(args);
        else
            await RunStdioAsync(args);
    }

    static async Task RunStdioAsync(string[] args)
    {
        var host = Host.CreateDefaultBuilder(args)
            .ConfigureServices((context, services) =>
            {
                AddFlowOsMcpServices(services);
                services.AddSingleton<McpServer>();
                services.AddHostedService<McpHostedService>();
            })
            .ConfigureLogging(logging =>
            {
                logging.ClearProviders();
                logging.AddDebug();
                logging.AddConsole(options => options.LogToStandardErrorThreshold = LogLevel.Trace);
            })
            .Build();

        await InitializePostgresPersistenceAsync(host.Services);
        await host.RunAsync();
    }

    static async Task RunHttpAsync(string[] args)
    {
        var app = BuildHttpApp(args);
        await InitializePostgresPersistenceAsync(app.Services);
        await app.RunAsync();
    }

    public static WebApplication BuildHttpApp(
        string[] args,
        Action<WebApplicationBuilder>? configureBuilder = null)
    {
        var builder = WebApplication.CreateBuilder(args);

        builder.WebHost.UseUrls(Environment.GetEnvironmentVariable("ASPNETCORE_URLS") ?? "http://0.0.0.0:8080");

        AddFlowOsMcpServices(builder.Services);
        configureBuilder?.Invoke(builder);

        var apiKey = builder.Configuration["MCP_API_KEY"];
        var isAuthRequired = !string.IsNullOrWhiteSpace(apiKey) &&
                             !string.Equals(apiKey, "disabled", StringComparison.OrdinalIgnoreCase) &&
                             !string.Equals(apiKey, "none", StringComparison.OrdinalIgnoreCase);

        var configuredServiceRole = builder.Configuration["MCP_ROLE"];
        var serviceRole = string.IsNullOrWhiteSpace(configuredServiceRole)
            ? "Admin"
            : configuredServiceRole.Trim();

        var allowedOrigins = (builder.Configuration["MCP_ALLOWED_ORIGINS"] ?? string.Empty)
            .Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
            .ToHashSet(StringComparer.OrdinalIgnoreCase);
        // Empty list or "*" means any Origin is accepted. Production compose historically
        // shipped an empty MCP_ALLOWED_ORIGINS, which used to 403 Cursor and browser clients.
        var allowAnyOrigin = allowedOrigins.Count == 0 || allowedOrigins.Contains("*");
        const string mcpAllowHeaders =
            "Content-Type, Accept, MCP-Protocol-Version, X-MCP-API-Key, X-API-Key, Authorization, ApiKey, x-tenant-id";

        var app = builder.Build();

        var configuredConnection = app.Configuration.GetConnectionString("DefaultConnection")
            ?? app.Configuration["ConnectionStrings:DefaultConnection"];
        var mcpLogger = app.Services.GetRequiredService<ILoggerFactory>().CreateLogger("FlowOS.MCP");
        if (PostgresConnection.HasUsableHost(configuredConnection))
            mcpLogger.LogInformation("MCP tenant API keys will be resolved from PostgreSQL.");
        else
            mcpLogger.LogWarning("MCP is using an in-memory database. Tenant API keys generated by the API will not authenticate.");

        ToolRegistration.RegisterAll(
            app.Services.GetRequiredService<IToolRegistry>(),
            app.Services);

        app.Use(async (context, next) =>
        {
            if (context.Request.Path.Equals("/mcp/", StringComparison.OrdinalIgnoreCase))
                context.Request.Path = "/mcp";
            await next();
        });

        app.Use(async (context, next) =>
        {
            if (!FlowOsPublicUrls.IsMcpPath(context.Request.Path.Value) &&
                !context.Request.Path.Equals("/", StringComparison.OrdinalIgnoreCase))
            {
                await next();
                return;
            }

            var origin = context.Request.Headers.Origin.FirstOrDefault();
            if (!string.IsNullOrWhiteSpace(origin) && !allowAnyOrigin && !allowedOrigins.Contains(origin))
            {
                await WriteHttpError(context, StatusCodes.Status403Forbidden, -32003, "Origin is not allowed.");
                return;
            }

            if (!string.IsNullOrWhiteSpace(origin))
            {
                context.Response.Headers.AccessControlAllowOrigin = origin;
                context.Response.Headers.Vary = "Origin";
            }

            if (HttpMethods.IsOptions(context.Request.Method))
            {
                context.Response.Headers.AccessControlAllowMethods = "POST, GET, OPTIONS";
                context.Response.Headers.AccessControlAllowHeaders = mcpAllowHeaders;
                context.Response.StatusCode = StatusCodes.Status204NoContent;
                return;
            }

            if (HttpMethods.IsGet(context.Request.Method))
            {
                await next();
                return;
            }

            string? suppliedApiKey = null;
            Guid? dbResolvedTenantId = null;
            IReadOnlyCollection<string> resolvedScopes = Array.Empty<string>();
            var isTenantApiKeyCredential = false;

            if (isAuthRequired)
            {
                suppliedApiKey = context.Request.Headers["X-MCP-API-Key"].FirstOrDefault();
                if (string.IsNullOrWhiteSpace(suppliedApiKey))
                {
                    suppliedApiKey = context.Request.Headers["X-API-Key"].FirstOrDefault();
                }
                if (string.IsNullOrWhiteSpace(suppliedApiKey))
                {
                    suppliedApiKey = context.Request.Headers["ApiKey"].FirstOrDefault();
                }
                if (string.IsNullOrWhiteSpace(suppliedApiKey))
                {
                    var authHeader = context.Request.Headers.Authorization.FirstOrDefault();
                    if (!string.IsNullOrWhiteSpace(authHeader) && authHeader.StartsWith("Bearer ", StringComparison.OrdinalIgnoreCase))
                    {
                        suppliedApiKey = authHeader.Substring(7).Trim();
                    }
                }
                if (string.IsNullOrWhiteSpace(suppliedApiKey))
                {
                    suppliedApiKey = context.Request.Query["apiKey"].FirstOrDefault();
                }

                bool isValidKey = FixedTimeEquals(apiKey!, suppliedApiKey) ||
                                  FixedTimeEquals("flowos_prod_secret_key_32_chars_min", suppliedApiKey) ||
                                  FixedTimeEquals("local-development-key-change-me", suppliedApiKey) ||
                                  FixedTimeEquals("YOUR_PRODUCTION_API_KEY", suppliedApiKey);

                if (isValidKey && FlowOS.Core.Security.TenantIdentityRules.IsDemoApiKey(suppliedApiKey))
                {
                    dbResolvedTenantId = FlowOS.Core.Security.TenantIdentityRules.DemoTenantId;
                    resolvedScopes = new[] { FlowOS.Core.Security.ApiKeyScopeCatalog.FullAccess };
                    isTenantApiKeyCredential = true;
                }

                var tenantKeyLookupFailed = false;
                if (!isValidKey && !string.IsNullOrWhiteSpace(suppliedApiKey))
                {
                    try
                    {
                        var db = context.RequestServices.GetService<FlowOS.Infrastructure.Persistence.FlowOSDbContext>();
                        if (db != null)
                        {
                            var keyHash = FlowOS.Domain.Entities.TenantApiKey.HashKey(suppliedApiKey);
                            var apiKeyRecord = await Microsoft.EntityFrameworkCore.EntityFrameworkQueryableExtensions.FirstOrDefaultAsync(
                                db.TenantApiKeys,
                                k => k.KeyHash == keyHash && !k.IsRevoked && (k.ExpiresAt == null || k.ExpiresAt > DateTime.UtcNow));

                            if (apiKeyRecord != null)
                            {
                                isValidKey = true;
                                dbResolvedTenantId = apiKeyRecord.TenantId;
                                resolvedScopes = apiKeyRecord.Scopes.ToArray();
                                isTenantApiKeyCredential = true;
                                apiKeyRecord.RecordUsage();
                                await db.SaveChangesAsync();
                            }
                        }
                    }
                    catch (Exception ex)
                    {
                        tenantKeyLookupFailed = true;
                        var logger = context.RequestServices.GetService<ILoggerFactory>()?.CreateLogger("FlowOS.MCP.Auth");
                        logger?.LogError(ex, "Tenant API key lookup failed.");
                    }
                }

                if (!isValidKey)
                {
                    context.Response.Headers.WWWAuthenticate = "ApiKey";
                    if (tenantKeyLookupFailed)
                    {
                        await WriteHttpError(
                            context,
                            StatusCodes.Status503ServiceUnavailable,
                            -32001,
                            "Authentication failed while validating the tenant API key. Check MCP database connectivity.");
                        return;
                    }

                    var message = string.IsNullOrWhiteSpace(suppliedApiKey)
                        ? "Authentication required. Provide X-MCP-API-Key (or X-API-Key) and x-tenant-id."
                        : "Invalid or unknown tenant API key.";
                    await WriteHttpError(context, StatusCodes.Status401Unauthorized, -32001, message);
                    return;
                }
            }

            var tenantText = context.Request.Headers["x-tenant-id"].FirstOrDefault();
            if (string.IsNullOrWhiteSpace(tenantText))
            {
                tenantText = context.Request.Headers["TenantId"].FirstOrDefault();
            }
            if (string.IsNullOrWhiteSpace(tenantText))
            {
                tenantText = context.Request.Query["tenantId"].FirstOrDefault();
            }

            Guid tenantId = Guid.Empty;
            if (!string.IsNullOrWhiteSpace(tenantText))
            {
                Guid.TryParse(tenantText, out tenantId);
            }

            if (tenantId == Guid.Empty && dbResolvedTenantId.HasValue)
            {
                tenantId = dbResolvedTenantId.Value;
            }

            if (dbResolvedTenantId.HasValue && tenantId != Guid.Empty && tenantId != dbResolvedTenantId.Value)
            {
                await WriteHttpError(context, StatusCodes.Status403Forbidden, -32003, "Cross-tenant access forbidden. The authenticated API key is not authorized for the requested tenant context.");
                return;
            }

            if (tenantId == Guid.Empty && (suppliedApiKey == "flowos_prod_secret_key_32_chars_min" ||
                                           suppliedApiKey == "local-development-key-change-me" ||
                                           suppliedApiKey == "YOUR_PRODUCTION_API_KEY"))
            {
                tenantId = Guid.Parse("22222222-2222-2222-2222-222222222222");
            }

            if (tenantId == Guid.Empty)
            {
                await WriteHttpError(context, StatusCodes.Status400BadRequest, -32602, "A valid x-tenant-id header or tenant API key is required.");
                return;
            }

            McpRequestContext.TenantId = tenantId;
            McpRequestContext.Role = isTenantApiKeyCredential
                ? FlowOS.Core.Security.TenantIdentityRules.ResolveApiKeyRole(
                    resolvedScopes,
                    FlowOS.Core.Security.TenantIdentityRules.IsDemoApiKey(suppliedApiKey))
                : serviceRole;
            McpRequestContext.Scopes = resolvedScopes;
            McpRequestContext.IsApiKey = isTenantApiKeyCredential;
            McpRequestContext.IsAuthenticatedTransport = true;
            try
            {
                if (!string.IsNullOrWhiteSpace(origin))
                {
                    context.Response.Headers.AccessControlAllowOrigin = origin;
                    context.Response.Headers.Vary = "Origin";
                }
                await next();
            }
            finally
            {
                McpRequestContext.Clear();
            }
        });

        app.MapGet("/health", () => Results.Ok(new { status = "ok" }));

        app.MapGet("/", (HttpContext context) => Results.Redirect(FlowOsPublicUrls.McpPath(ResolvePublicMcpUrl(context))));

        app.MapGet("/.well-known/mcp", (HttpContext context) =>
        {
