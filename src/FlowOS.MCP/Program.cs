        });

        app.MapGet("/.well-known/mcp.json", () => Results.Redirect("/.well-known/mcp"));
        app.MapGet("/sse", (HttpContext context) => Results.Redirect(FlowOsPublicUrls.McpPath(ResolvePublicMcpUrl(context))));

